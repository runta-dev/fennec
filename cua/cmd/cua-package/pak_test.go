func gz(t *testing.T, s string) []byte {
	var b bytes.Buffer
	w := gzip.NewWriter(&b)
	_, _ = w.Write([]byte(s))
	_ = w.Close()
	return b.Bytes()
}

func testPak(t *testing.T, data ...[]byte) []byte {
	p := &pak{encoding: 1, aliases: [][2]uint16{{900, 1}}}
	for i, d := range data {
		p.ids = append(p.ids, uint16(100+i))
		p.data = append(p.data, d)
	}
	return p.bytes()
}

func TestPak(t *testing.T) {
	const sample = "<html>sample credits</html>\n"
	packed := testPak(t, []byte("raw one"), gz(t, sample), gz(t, "other"))
	if binary.LittleEndian.Uint32(packed) != 5 {
		t.Fatal("not version 5")
	}
	p, err := parsePak(packed)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(p.bytes(), packed) || len(p.ids) != 3 || p.aliases[0] != [2]uint16{900, 1} {
		t.Fatalf("round trip %+v", p)
	}
	page := []byte("<!-- Generated by licenses.py; do not edit. --><p>credits</p>")
	out, id, err := replaceResource(packed, []byte(sample), page)
	if err != nil || id != 101 {
		t.Fatalf("%d %v", id, err)
	}
	q, err := parsePak(out)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(q.data[1], page) || !bytes.Equal(q.data[0], []byte("raw one")) || !bytes.Equal(q.data[2], p.data[2]) || q.aliases[0] != p.aliases[0] {
		t.Errorf("after the swap %q", q.data)
	}
	if _, _, err := replaceResource(testPak(t, gz(t, sample), []byte(sample)), []byte(sample), page); err == nil || !strings.Contains(err.Error(), "both") {
		t.Errorf("two placeholders: %v", err)
	}
	if _, _, err := replaceResource(testPak(t, []byte("x")), []byte(sample), page); err == nil {
		t.Error("no placeholder accepted")
	}
	if _, _, err := replaceResource(packed, []byte(sample), gz(t, "z")); err == nil {
		t.Error("a replacement that reads as compressed was accepted")
	}
	for _, bad := range [][]byte{nil, []byte("PAK!xxxxxxxxxxxxx"), packed[:20]} {
		if _, err := parsePak(bad); err == nil {
			t.Errorf("%q parsed", bad)
		}
	}
	// A Brotli header whose size does not match is not decoded.
	if _, ok := resourceText(append(append([]byte{}, brotliMagic...), 9, 0, 0, 0, 0, 0, 1, 2), 3); ok {
		t.Error("a mismatched Brotli size decoded")
	}
}

func fakeApp(t *testing.T, framework []byte) string {
	app := filepath.Join(t.TempDir(), chromium.AppName)
	fw := filepath.Join(app, "Contents", "Frameworks", "Chromium Framework.framework", "Versions", "160.0.1.0")
	for _, d := range []string{filepath.Join(fw, "Resources"), filepath.Join(app, "Contents", "Resources")} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.Symlink("160.0.1.0", filepath.Join(filepath.Dir(fw), "Current")); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(fw, "Chromium Framework"), framework, 0o755); err != nil {
		t.Fatal(err)
	}
	return app
}

func TestPatchSafeStorage(t *testing.T) {
	good := []byte("\x00\x01junk\x00\x00Chromium Safe Storage\x00Chromium\x00mock_password\x00tail")
	app := fakeApp(t, good)
	if err := patchSafeStorage(app); err != nil {
		t.Fatal(err)
	}
	fw, _ := frameworkDir(app)
	got, _ := os.ReadFile(filepath.Join(fw, "Chromium Framework"))
	want := bytes.Replace(good, []byte("Chromium Safe Storage\x00"), []byte("Fennec Safe Storage\x00\x00\x00"), 1)
	if !bytes.Equal(got, want) || len(got) != len(good) {
		t.Errorf("patched %q", got)
	}
	var m chromium.SafeStorage
	data, _ := os.ReadFile(filepath.Join(app, "Contents", "Resources", chromium.SafeStorageMarker))
	if err := json.Unmarshal(data, &m); err != nil || m.Service != "Fennec Safe Storage" || m.Account != "Chromium" {
		t.Errorf("marker %s %v", data, err)
	}
	if s, ok := chromium.SafeStorageOf(chromium.Executable(app)); !ok || s.Service != chromium.SafeStorageService {
		t.Errorf("the daemon does not see the marker: %v %v", s, ok)
	}
	for name, fw := range map[string][]byte{
		"missing":    []byte("\x00nothing here\x00"),
		"twice":      []byte("\x00Chromium Safe Storage\x00Chromium Safe Storage\x00"),
		"not alone":  []byte("xChromium Safe Storage\x00"),
		"at start":   []byte("Chromium Safe Storage\x00"),
		"no NUL end": []byte("\x00Chromium Safe Storage!"),
	} {
		if err := patchSafeStorage(fakeApp(t, fw)); err == nil {
			t.Errorf("%s: patched", name)
		}
	}
}
