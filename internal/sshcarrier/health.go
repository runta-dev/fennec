package sshcarrier

import (
	"bytes"
	"crypto/rand"
	"fennec/internal/launchprofile"
	"fmt"
	"io"
	"sync/atomic"
	"time"

	"golang.org/x/crypto/ssh"
)

type healthNetwork interface {
	Online() bool
	Changes() <-chan struct{}
}

type healthPolicy struct {
	interval time.Duration
	timeout  time.Duration
	network  healthNetwork
}

func defaultHealthPolicy() healthPolicy {
	return healthPolicy{interval: 2 * time.Second, timeout: 3 * time.Second}
}

// The local SSH lease can still answer while its WAN transport is blackholed.
// Only the worker owns that socket, so only the worker can reliably retire it.
// Probe even between daemon leases; ordinary lease release never revokes peers.
func (s *server) watchHealth(client *ssh.Client, ended <-chan struct{}, activity *atomic.Int64) {
	ticker := time.NewTicker(s.health.interval)
	defer ticker.Stop()
	var channel ssh.Channel
	for {
		select {
		case <-s.ctx.Done():
			return
		case <-ended:
			return
		case <-ticker.C:
		}
		network := s.health.network
		if network != nil && !network.Online() {
			continue
		}
		reply := make(chan error, 1)
		go func() {
			// SSH request acknowledgements may be generated by an intermediate
			// gateway. Echo unpredictable bytes through a tiny runtime process so
			// only the complete channel path can confirm liveness. This service
			// does not launch an agent, read files, or interpret its input.
			if channel == nil {
				opened, requests, err := client.OpenChannel("session", nil)
				if err != nil {
					reply <- err
					return
				}
				channel = opened
				go ssh.DiscardRequests(requests)
				go io.Copy(io.Discard, channel.Stderr())
				ok, err := channel.SendRequest("exec", true, ssh.Marshal(struct{ Command string }{"exec /bin/cat"}))
				if err != nil || !ok {
					if err == nil {
						err = fmt.Errorf("runtime health service refused")
					}
					reply <- err
					return
				}
			}
			var nonce, echoed [32]byte
			_, err := rand.Read(nonce[:])
			if err == nil {
				_, err = io.Copy(channel, bytes.NewReader(nonce[:]))
			}
			if err == nil {
				_, err = io.ReadFull(channel, echoed[:])
			}
			if err == nil && nonce != echoed {
				err = fmt.Errorf("runtime health response mismatch")
			}
			reply <- err
		}()
		timer := time.NewTimer(s.health.timeout)
		observedAfter := time.Now().UnixNano()
		online := true
		probing := true
		for probing {
			var changed <-chan struct{}
			if network != nil {
				changed = network.Changes()
				next := network.Online()
				if next != online {
					// Local offline time is not evidence of a dead remote peer.
					// Give the retained probe one bounded online interval to reply.
					timer.Reset(s.health.timeout)
					online = next
				}
			}
			select {
			case <-s.ctx.Done():
				timer.Stop()
				return
			case <-ended:
				timer.Stop()
				return
			case err := <-reply:
				timer.Stop()
				if err != nil {
					s.retire(client)
					return
				}
				probing = false
			case <-changed:
			case <-timer.C:
				if network != nil && !network.Online() {
					online = false
					timer.Reset(s.health.timeout)
					continue
				}
				// Actual runtime stdout/stderr proves that forwarding is making
				// progress. A busy connection may delay the echo behind other data.
				// Gateway keepalives and local lease traffic never update this value.
				if activity.Load() > observedAfter {
					observedAfter = time.Now().UnixNano()
					timer.Reset(s.health.timeout)
					continue
				}
				launchprofile.Record("ssh.carrier_retired_health", time.Now(), 0)
				s.retire(client)
				return
			}
		}
	}
}
