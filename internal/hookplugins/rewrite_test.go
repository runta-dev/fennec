func fixtureHook(t *testing.T, home, event string) string {
	t.Helper()
	body := []byte("#!/bin/sh\n# fixture-only cmux hook\nif [ -n \"$CMUX_SURFACE_ID\" ]; then printf '{}'; fi\n")
	sum := sha256.Sum256(body)
	dir := filepath.Join(home, ".cmux/hooks")
	if err := os.MkdirAll(dir, 0700); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, "cmux-codex-hook-"+hex.EncodeToString(sum[:8])+"-"+event+".sh")
	if err := os.WriteFile(path, body, 0700); err != nil {
		t.Fatal(err)
	}
	return path
}
func TestRewriteOnlyCmuxHandlerPreservesOtherHooksAndPrompt(t *testing.T) {
	home := filepath.Join(t.TempDir(), "space in home")
	path := fixtureHook(t, home, "session-start")
	config := `hooks.SessionStart=[{matcher="startup",hooks=[{type="command",command='''` + "'" + path + "'" + `''',timeout=5000},{type="command",command="company-audit --keep",timeout=9000}]}]`
	prompt := "hooks.SessionStart=some literal cmux text"
	args := []string{"--enable", "hooks", "--dangerously-bypass-hook-trust", "-c", config, "--", prompt}
	result, count, err := Rewrite(home, "petite-neat", "codex", args, fixtureContext(t, home))
	if err != nil || len(count) != 1 {
		t.Fatalf("rewrite bindings=%v err=%v result=%q", count, err, result)
	}
	if result[len(result)-1] != prompt || args[4] != config || !strings.Contains(result[4], `command="company-audit --keep",timeout=9000`) {
		t.Fatal("unrelated arguments or hook changed")
	}
	var decoded map[string]any
	if err := toml.Unmarshal([]byte(result[4]), &decoded); err != nil {
		t.Fatal("replacement is not TOML", err)
	}
	if strings.Contains(result[4], path) || !strings.Contains(result[4], " hook petite-neat ") {
		t.Fatal("Mac hook path survived", result[4])
	}
}
func TestUnrelatedOrChangedHookIsNotSilentlyReplaced(t *testing.T) {
	home := t.TempDir()
	path := fixtureHook(t, home, "stop")
	config := `hooks.Stop=[{hooks=[{type="command",command='''` + path + `'''}]}]`
	if err := os.WriteFile(path, []byte("#!/bin/sh\n# CMUX_SURFACE_ID altered\n"), 0700); err != nil {
		t.Fatal(err)
	}
	if _, _, err := Rewrite(home, "petite-neat", "codex", []string{"--config=" + config}, fixtureContext(t, home)); err == nil {
		t.Fatal("modified content-addressed hook accepted")
	}
	other := `hooks.Stop=[{hooks=[{type="command",command="/Users/user/custom-hook.sh"}]}]`
	result, n, err := Rewrite(home, "petite-neat", "codex", []string{"--config", other}, fixtureContext(t, home))
	if err != nil || len(n) != 0 || result[1] != other {
		t.Fatal("user hook changed")
	}
}
func TestOfficialCmuxInjection(t *testing.T) {
	path := os.Getenv("FENNEC_CMUX_INJECT_FIXTURE")
	home := os.Getenv("FENNEC_CMUX_FIXTURE_HOME")
	binary := os.Getenv("FENNEC_CMUX_BINARY")
	if path == "" && binary == "" {
		t.Skip("explicit downloaded cmux artifact required")
	}
	var raw []byte
	var err error
	if binary != "" {
		home = shortHome(t)
		command := exec.Command(binary, "hooks", "codex", "inject-args")
		command.Env = []string{"HOME=" + home, "CFFIXED_USER_HOME=" + home, "CODEX_HOME=" + filepath.Join(home, ".codex"), "PATH=/usr/bin:/bin"}
		raw, err = command.Output()
	} else {
		raw, err = os.ReadFile(path)
	}
	if err != nil {
		t.Fatal(err)
	}
	args := strings.Split(strings.TrimSuffix(string(raw), "\x00"), "\x00")
	result, n, err := Rewrite(home, "petite-neat", "codex", args, fixtureContext(t, home))
	if err != nil || len(n) < 8 {
		t.Fatalf("official cmux hook generation unsupported: bindings=%v error=%v", n, err)
	}
	for _, arg := range result {
		if strings.HasPrefix(arg, "hooks.") {
			var value map[string]any
			if err := toml.Unmarshal([]byte(arg), &value); err != nil {
				t.Fatal(err)
			}
			if strings.Contains(arg, filepath.Join(home, ".cmux/hooks")) {
				t.Fatal("local path forwarded to sandbox")
			}
		}
	}
	t.Logf("rewrote %d bindings generated by official cmux", len(n))
}

func fixtureContext(t *testing.T, home string) Context {
	t.Helper()
	os.MkdirAll(home, 0700)
	path := filepath.Join(home, "cmux")
	if _, err := os.Stat(path); os.IsNotExist(err) {
		if err := os.WriteFile(path, []byte("#!/bin/sh\nprintf '{}'\n"), 0700); err != nil {
			t.Fatal(err)
		}
	}
	return Context{Cmux: &cmuxhooks.Local{Executable: path, Workspace: "11111111-1111-4111-8111-111111111111", Surface: "22222222-2222-4222-8222-222222222222", Env: []string{"HOME=" + home, "PATH=/usr/bin:/bin"}}}
}
func shortHome(t *testing.T) string {
	t.Helper()
	dir, err := os.MkdirTemp("/tmp", "fn-hook-plugin-")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { os.RemoveAll(dir) })
	return dir
}
