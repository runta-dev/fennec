// Background rerenders must preserve the in-flight native login control state.
const loginActions=[];
let loginButtons=[];
const nativeLogin=vm.createContext({window:{},send:action=>loginActions.push(action),document:{querySelectorAll:()=>loginButtons}});
vm.runInContext(fs.readFileSync('native/macos/UI/agent-login.js','utf8'),nativeLogin);
const loginButton=()=>({dataset:{agent:'claude'},disabled:false,attributes:{},setAttribute(k,v){this.attributes[k]=v},removeAttribute(k){delete this.attributes[k]}});
let button=loginButton();loginButtons=[button];
nativeLogin.window.configureAgentLoginControl(button,true);
nativeLogin.window.startAgentLogin('claude');
assert.equal(button.disabled,true);
assert.equal(button.attributes['aria-busy'],'true');
button=loginButton();loginButtons=[button];
nativeLogin.window.configureAgentLoginControl(button,true);
assert.equal(button.disabled,true,'rerender must retain pending state');
nativeLogin.window.startAgentLogin('claude');
assert.equal(loginActions.length,1,'pending login must not dispatch twice');
nativeLogin.window.renderAgentLoginStarted(null,'claude');
assert.equal(button.disabled,false,'failed opening must allow another attempt');
assert.equal(button.attributes['aria-busy'],undefined);
nativeLogin.window.startAgentLogin('claude');
nativeLogin.window.configureAgentLoginControl(button,false);
nativeLogin.window.renderAgentLoginStarted({},'claude');
assert.equal(button.disabled,true,'completion must not enable an unavailable route');
nativeLogin.window.configureAgentLoginControl(button,true);
nativeLogin.window.startAgentLogin('claude');
nativeLogin.window.resetAgentLogin();
assert.equal(button.disabled,false);
assert.equal(button.attributes['aria-busy'],undefined);
console.log('PASS native login pending state across rerender, failure, route loss, and reset');
